/* Day metrics UI — wait/ride chips, day totals, and the route tracer.
   Reads window.DAY_METRICS (generated by build-day-metrics.py).
   ponytail: one data table, one render pass. No framework, no build step. */
(function () {
  'use strict';
  var M = window.DAY_METRICS;
  if (!M) return;
  var META = window.DAY_METRICS_META || { pathFactor: 1.35, strideM: 0.72 };

  var KIND = {
    ride:    { icon: '\u{1F3A2}', noun: 'ride' },
    show:    { icon: '\u{1F3AD}', noun: 'show' },
    meet:    { icon: '\u{1F58A}', noun: 'meet' },
    meal:    { icon: '\u{1F374}', noun: 'table' },
    walk:    { icon: '\u{1F6B6}', noun: 'on foot' },
    transit: { icon: '\u{1F68C}', noun: 'travel' },
    app:     { icon: '\u{1F4F1}', noun: 'in the app' },
    rest:    { icon: '\u{1F634}', noun: 'rest' }
  };

  function hm(mins) {
    var h = Math.floor(mins / 60), m = Math.round(mins % 60);
    if (!h) return m + 'm';
    return h + 'h' + (m ? ' ' + (m < 10 ? '0' : '') + m + 'm' : '');
  }
  function miles(metres) { return (metres / 1609.344).toFixed(1); }
  function commas(n) { return String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ','); }

  /* ---- 1. per-stop chips ------------------------------------------------ */
  function chips(day) {
    var arts = document.getElementById(day);
    if (!arts) return;
    var data = M[day];
    arts.querySelectorAll('li.ed-ev').forEach(function (li) {
      var numEl = li.querySelector('.ed-num');
      if (!numEl) return;
      var s = data.stops[numEl.textContent.trim()];
      if (!s) return;
      var k = KIND[s.k] || KIND.walk;
      var row = document.createElement('span');
      row.className = 'ed-mx' + (s.alt ? ' is-alt' : '');
      var html = '';
      if (s.w > 0) {
        html += '<b class="mx-w"><i aria-hidden="true">⏳</i>' + hm(s.w) +
                ' <em>in line</em></b>';
      } else {
        html += '<b class="mx-w mx-none"><i aria-hidden="true">✓</i>no queue</b>';
      }
      if (s.e > 0) {
        html += '<b class="mx-e"><i aria-hidden="true">' + k.icon + '</i>' +
                hm(s.e) + ' <em>' + k.noun + '</em></b>';
      }
      html += '<b class="mx-t">' + hm(s.w + s.e) + ' <em>total</em></b>';
      if (s.alt) html += '<b class="mx-alt">either/or — not added to the day</b>';
      row.innerHTML = html;
      var body = li.querySelector('.ed-body');
      (body || li).appendChild(row);
    });
  }

  /* ---- 2. day totals in the header deck --------------------------------- */
  function totals(day) {
    var art = document.getElementById(day);
    if (!art) return;
    var dek = art.querySelector('.ed-dek');
    if (!dek) return;
    var d = M[day];
    var ratio = d.rideShowMin ? (d.waitMin / d.rideShowMin) : 0;
    var add = [
      ['In line', hm(d.waitMin)],
      ['On rides &amp; shows', hm(d.rideShowMin)],
      ['Meals, rest &amp; travel', hm(d.otherMin)],
      ['On foot', commas(d.steps) + ' steps'],
      ['Queued per ride minute', ratio ? ratio.toFixed(1) + '×' : '—']
    ];
    add.forEach(function (p) {
      var sp = document.createElement('span');
      sp.className = 'dek-mx';
      sp.innerHTML = '<i>' + p[0] + '</i>' + p[1];
      dek.appendChild(sp);
    });
  }

  /* ---- 3. route tracer --------------------------------------------------- */
  function tracer(day) {
    var art = document.getElementById(day);
    if (!art) return;
    var d = M[day], route = d.route;
    if (!route || route.length < 2) return;

    // Stop headings, so the readout can name where you are.
    var names = {};
    art.querySelectorAll('li.ed-ev').forEach(function (li) {
      var n = li.querySelector('.ed-num'), h = li.querySelector('.ed-h');
      if (n && h) {
        names[n.textContent.trim()] =
          h.textContent.replace(/\s+/g, ' ').trim()
           .replace(/(Transit|In the app|Pandora|Africa|Asia|Discovery Island|The Oasis)$/, '').trim();
      }
    });

    // Equirectangular projection: at 28°N one degree of longitude is
    // cos(28°) ≈ 0.883 as long as one degree of latitude.
    var LON_SCALE = Math.cos(28.4 * Math.PI / 180);
    var xs = route.map(function (p) { return p.lon * LON_SCALE; });
    var ys = route.map(function (p) { return -p.lat; });
    var minX = Math.min.apply(null, xs), maxX = Math.max.apply(null, xs);
    var minY = Math.min.apply(null, ys), maxY = Math.max.apply(null, ys);
    var spanX = (maxX - minX) || 1e-6, spanY = (maxY - minY) || 1e-6;
    var PAD = 34, W = 1000, H = Math.max(420, Math.min(760,
      Math.round((spanY / spanX) * (W - PAD * 2)) + PAD * 2));

    var pts = route.map(function (p, i) {
      return {
        n: p.n, cum: p.cum, leg: p.leg,
        x: PAD + ((xs[i] - minX) / spanX) * (W - PAD * 2),
        y: PAD + ((ys[i] - minY) / spanY) * (H - PAD * 2)
      };
    });

    var path = pts.map(function (p, i) {
      return (i ? 'L' : 'M') + p.x.toFixed(1) + ' ' + p.y.toFixed(1);
    }).join(' ');

    var dots = pts.map(function (p, i) {
      return '<g class="tr-stop" data-i="' + i + '">' +
        // Transparent hit circle: the dots render ~12 CSS px across on a phone,
        // which is not a tappable target. This gives each stop a ~44px one.
        '<circle class="tr-hit" cx="' + p.x.toFixed(1) + '" cy="' + p.y.toFixed(1) +
        '" r="50"/>' +
        '<circle class="tr-dot" cx="' + p.x.toFixed(1) + '" cy="' + p.y.toFixed(1) +
        '" r="18"/>' +
        '<text class="tr-lab" x="' + p.x.toFixed(1) + '" y="' + (p.y + 6.5).toFixed(1) +
        '">' + p.n + '</text></g>';
    }).join('');

    var fig = document.createElement('figure');
    fig.className = 'ed-trace';
    fig.innerHTML =
      '<figcaption class="tr-head">' +
        '<b>Route tracer</b>' +
        '<span>' + d.label + ' · ' + d.date + ' · ' + route.length +
        ' mapped stops · ' + miles(d.metres) + ' mi · ' +
        commas(d.steps) + ' steps</span>' +
      '</figcaption>' +
      '<div class="tr-wrap">' +
        '<svg viewBox="0 0 ' + W + ' ' + H + '" role="img" ' +
             'aria-label="Walking route for ' + d.label + ', stop 1 to stop ' +
             route[route.length - 1].n + '">' +
          '<path class="tr-base" d="' + path + '"/>' +
          '<path class="tr-done" d="' + path + '"/>' +
          '<circle class="tr-you" r="26" cx="' + pts[0].x.toFixed(1) +
          '" cy="' + pts[0].y.toFixed(1) + '"/>' +
          dots +
        '</svg>' +
      '</div>' +
      '<div class="tr-ctl">' +
        '<input class="tr-range" type="range" min="0" max="' + (pts.length - 1) +
        '" value="0" step="1" aria-label="Progress through the day">' +
        '<div class="tr-read">' +
          '<div class="tr-now"><i>Stop</i><b class="tr-n"></b></div>' +
          '<div><i>Walked</i><b class="tr-d"></b></div>' +
          '<div><i>Steps</i><b class="tr-s"></b></div>' +
          '<div><i>Time on the clock</i><b class="tr-t"></b></div>' +
        '</div>' +
      '</div>' +
      '<p class="tr-foot">Straight-line distance between real attraction ' +
        'coordinates × ' + META.pathFactor + ' for winding walkways, at a ' +
        META.strideM + ' m stride. Stop to stop only — queue switchbacks, ' +
        'wrong turns and wandering all add more. Bus, Skyliner and car legs are ' +
        'not counted as walking.</p>';

    var map = art.querySelector('.ed-map');
    if (map && map.parentNode) map.parentNode.insertBefore(fig, map.nextSibling);
    else art.querySelector('.ed-spread-in').appendChild(fig);

    // Cumulative elapsed minutes (wait + experience) up to each mapped stop.
    var elapsed = [], run = 0, byNum = d.stops;
    var allNums = Object.keys(byNum).map(Number).sort(function (a, b) { return a - b; });
    var mapped = {};
    pts.forEach(function (p) { mapped[p.n] = true; });
    allNums.forEach(function (n) {
      var s = byNum[String(n)];
      if (!s.alt) run += s.w + s.e;
      if (mapped[n]) elapsed.push(run);
    });

    var svg = fig.querySelector('svg');
    var done = fig.querySelector('.tr-done');
    var you = fig.querySelector('.tr-you');
    var range = fig.querySelector('.tr-range');
    var len = done.getTotalLength();
    done.style.strokeDasharray = len;

    function lengthAt(i) {
      // Path length up to point i, measured on the rendered path.
      if (i <= 0) return 0;
      var acc = 0;
      for (var k = 1; k <= i; k++) {
        acc += Math.hypot(pts[k].x - pts[k - 1].x, pts[k].y - pts[k - 1].y);
      }
      return acc;
    }
    var fullPx = lengthAt(pts.length - 1) || 1;

    function draw(i) {
      var p = pts[i];
      done.style.strokeDashoffset = len - (lengthAt(i) / fullPx) * len;
      you.setAttribute('cx', p.x.toFixed(1));
      you.setAttribute('cy', p.y.toFixed(1));
      svg.querySelectorAll('.tr-stop').forEach(function (g, k) {
        g.classList.toggle('is-done', k <= i);
        g.classList.toggle('is-now', k === i);
      });
      fig.querySelector('.tr-n').textContent =
        p.n + (names[p.n] ? ' · ' + names[p.n] : '');
      fig.querySelector('.tr-d').textContent = miles(p.cum) + ' mi';
      fig.querySelector('.tr-s').textContent =
        commas(Math.round(p.cum / META.strideM)) + ' steps';
      fig.querySelector('.tr-t').textContent = hm(elapsed[i] || 0);
    }
    range.addEventListener('input', function () { draw(+range.value); });
    svg.querySelectorAll('.tr-stop').forEach(function (g) {
      g.addEventListener('click', function () {
        range.value = g.dataset.i;
        draw(+g.dataset.i);
      });
    });
    draw(0);
  }

  Object.keys(M).forEach(function (day) {
    chips(day);
    totals(day);
    tracer(day);
  });
})();
